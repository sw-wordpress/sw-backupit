#!/usr/bin/env php
<?php

declare(strict_types=1);

/**
 * Compiles the .po files into plain PHP array catalogs for the standalone restore application (packages/restore/lang/<language>.php).
 * Only entries referenced from the restore wizard views or the generated core message list are included.
 */

$root = dirname(__DIR__);
$map = ['de_DE' => 'de', 'fr_FR' => 'fr', 'pl_PL' => 'pl', 'it_IT' => 'it'];
@mkdir($root . '/packages/restore/lang', 0775, true);

/** @return array<string, string> */
function parse_po(string $file): array
{
    $entries = [];
    $reference = '';
    $current = null;
    $msgid = $msgstr = '';
    $references = '';
    $state = '';
    $flush = static function () use (&$entries, &$msgid, &$msgstr, &$references): void {
        if ($msgid !== '' && $msgstr !== '' && (str_contains($references, 'packages/restore/src/Web/') || str_contains($references, 'Support/CoreMessages.php'))) {
            $entries[$msgid] = $msgstr;
        }
        $msgid = $msgstr = $references = '';
    };
    foreach (file($file, FILE_IGNORE_NEW_LINES) ?: [] as $line) {
        if (str_starts_with($line, '#:')) {
            if ($state === 'msgstr') {
                $flush();
                $state = '';
            }
            $references .= $line . "\n";
        } elseif (str_starts_with($line, 'msgid "')) {
            if ($state === 'msgstr') {
                $flush();
            }
            $msgid = stripcslashes(substr($line, 7, -1));
            $state = 'msgid';
        } elseif (str_starts_with($line, 'msgstr "')) {
            $msgstr = stripcslashes(substr($line, 8, -1));
            $state = 'msgstr';
        } elseif (str_starts_with($line, '"')) {
            $value = stripcslashes(substr($line, 1, -1));
            if ($state === 'msgid') {
                $msgid .= $value;
            } elseif ($state === 'msgstr') {
                $msgstr .= $value;
            }
        } elseif ($line === '' && $state === 'msgstr') {
            $flush();
            $state = '';
        }
    }
    if ($state === 'msgstr') {
        $flush();
    }

    return $entries;
}

foreach ($map as $locale => $language) {
    $po = $root . "/languages/sw-backupit-{$locale}.po";
    if (!is_file($po)) {
        continue;
    }
    $entries = parse_po($po);
    ksort($entries);
    file_put_contents(
        $root . "/packages/restore/lang/{$language}.php",
        "<?php\n\n// GENERATED by bin/i18n-restore.php from languages/sw-backupit-{$locale}.po - do not edit.\n\nreturn " . var_export($entries, true) . ";\n",
    );
    fwrite(STDOUT, "{$language}: " . count($entries) . " strings\n");
}
