#!/usr/bin/env php
<?php

declare(strict_types=1);

/**
 * Generates packages/wordpress/src/Support/CoreMessages.php: a list of every static user-facing message of the framework
 * independent core and restore packages (exception messages, test restore details, ...) as literal __() calls.
 * xgettext can then extract them into the .pot, and the WordPress adapter translates core messages at presentation time.
 * Run through bin/i18n.sh (pot/update).
 */

$root = dirname(__DIR__);
$messages = [];
foreach (['packages/core/src', 'packages/restore/src'] as $directory) {
    $iterator = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($root . '/' . $directory, FilesystemIterator::SKIP_DOTS));
    foreach ($iterator as $file) {
        if ($file->getExtension() !== 'php' || str_contains($file->getPathname(), '/Web/View.php') || str_contains($file->getPathname(), '/Cli/')) {
            continue;
        }
        $tokens = token_get_all((string) file_get_contents($file->getPathname()));
        $count = count($tokens);
        for ($i = 0; $i < $count; $i++) {
            if (!is_array($tokens[$i]) || $tokens[$i][0] !== T_NEW) {
                continue;
            }
            $j = $i + 1;
            $class = '';
            while ($j < $count && (is_array($tokens[$j]) && in_array($tokens[$j][0], [T_STRING, T_NS_SEPARATOR, T_NAME_QUALIFIED, T_NAME_FULLY_QUALIFIED, T_WHITESPACE], true))) {
                $class .= is_array($tokens[$j]) ? $tokens[$j][1] : '';
                $j++;
            }
            if (!str_ends_with(trim($class), 'Exception') || ($tokens[$j] ?? null) !== '(') {
                continue;
            }
            $j++;
            while (is_array($tokens[$j] ?? null) && $tokens[$j][0] === T_WHITESPACE) {
                $j++;
            }
            if (is_array($tokens[$j] ?? null) && $tokens[$j][0] === T_CONSTANT_ENCAPSED_STRING) {
                // Only literals that are the complete first argument (not "'a' . $b").
                $next = $j + 1;
                while (is_array($tokens[$next] ?? null) && $tokens[$next][0] === T_WHITESPACE) {
                    $next++;
                }
                if (in_array($tokens[$next] ?? null, [',', ')'], true)) {
                    $value = eval('return ' . $tokens[$j][1] . ';');
                    if (is_string($value) && $value !== '') {
                        $messages[$value] = true;
                    }
                }
            }
        }
    }
}
// Additional static messages that are not exceptions.
$extra = [
    'No account with CREATE DATABASE privilege available.',
    'The scratch database could not be created (missing privilege).',
    'Files and database restored into the isolated environment.',
    'The WordPress options table is readable (siteurl present).',
    'siteurl option missing in the restored database.',
    'Backup verification failed',
    'Symbolic links from the backup were not recreated (security policy). Recreate them manually if needed:',
    'wp-config.php was not found in the target; database settings were not updated.',
    'These files changed while the backup was running; their restored content may be inconsistent:',
    'Some database settings in wp-config.php are not plain values and were NOT updated. Check them before using the site:',
];
foreach ($extra as $message) {
    $messages[$message] = true;
}
$messages = array_keys($messages);
sort($messages);

$out = "<?php\n/**\n * GENERATED by bin/i18n-core-messages.php - do not edit.\n *\n * Static messages of the framework independent core/restore packages as literal gettext calls so they can be extracted into the\n * .pot file. translate() looks a message up in the active catalog at presentation time (REST errors, job errors, notifications).\n *\n * @package SWBackupIt\n */\n\ndeclare(strict_types=1);\n\nnamespace SWBackupIt\\WordPress\\Support;\n\nfinal class CoreMessages {\n\n\t/**\n\t * Translates a core message when the catalog knows it; unknown (e.g. dynamic) messages are returned unchanged.\n\t *\n\t * @param string \$message English message produced by the core.\n\t */\n\tpublic static function translate( string \$message ): string {\n\t\t// phpcs:ignore WordPress.WP.I18n.NonSingularStringLiteralText -- runtime lookup of catalog entries declared in catalog().\n\t\treturn __( \$message, 'sw-backupit' );\n\t}\n\n\t/**\n\t * Declares the translatable core messages (never executed, only scanned by xgettext).\n\t *\n\t * @return list<string>\n\t */\n\tpublic static function catalog(): array {\n\t\treturn array(\n";
foreach ($messages as $message) {
    $out .= "\t\t\t__( " . var_export($message, true) . ", 'sw-backupit' ),\n";
}
$out .= "\t\t);\n\t}\n}\n";
file_put_contents($root . '/packages/wordpress/src/Support/CoreMessages.php', $out);
fwrite(STDOUT, count($messages) . " core messages\n");
